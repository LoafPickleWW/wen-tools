/**
 * Compile contracts/VoteTool.algo.ts (puya-ts, AVM v13) and record the Vote template's program
 * hash in src/utils/voteTemplates.ts. Earlier hashes are kept, because votes created from older
 * templates still exist on-chain.
 *
 *   pnpm build:vote-contracts
 */
import { execSync } from "node:child_process";
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { sha512_256 } from "@noble/hashes/sha2.js";

execSync("npx puya-ts contracts/VoteTool.algo.ts --out-dir build/vote --output-bytecode", { stdio: "inherit" });

const program = readFileSync("contracts/build/vote/Vote.approval.bin");
const hash = Buffer.from(sha512_256(Buffer.concat([Buffer.from("Program"), program]))).toString("hex");

const file = "src/utils/voteTemplates.ts";
const known = existsSync(file) ? [...readFileSync(file, "utf8").matchAll(/"([0-9a-f]{64})"/g)].map((m) => m[1]) : [];
const hashes = known.includes(hash) ? known : [...known, hash];

// algod reports a failed assert as "pc=N" only; map program counters back to the source messages.
const errorMap = (name) => {
  const arc56 = JSON.parse(readFileSync(`contracts/build/vote/${name}.arc56.json`, "utf8"));
  const out = {};
  for (const info of arc56.sourceInfo?.approval?.sourceInfo ?? []) {
    if (info.errorMessage) for (const pc of info.pc) out[pc] = info.errorMessage;
  }
  return out;
};
const errors = { vote: errorMap("Vote"), factory: errorMap("VoteFactory"), list: errorMap("VoterList") };

// Creation deposit the protocol charges the CREATOR of an app (the factory, for child apps):
// 100,000 per program page + 28,500 per global uint + 50,000 per global byte slice.
const appDeposit = (name) => {
  const { global } = JSON.parse(readFileSync(`contracts/build/vote/${name}.arc56.json`, "utf8")).state.schema;
  const size = readFileSync(`contracts/build/vote/${name}.approval.bin`).length;
  const pages = Math.ceil(size / 2048);
  return 100_000 * pages + 28_500 * global.ints + 50_000 * global.bytes;
};
const deposits = { vote: appDeposit("Vote"), list: appDeposit("VoterList"), registry: appDeposit("VoteRegistry"), factory: appDeposit("VoteFactory") };

writeFileSync(
  file,
  `// Generated by scripts/build-vote-contracts.mjs. Newest last.\nexport const KNOWN_VOTE_TEMPLATES: string[] = [\n${hashes
    .map((h) => `  "${h}",`)
    .join("\n")}\n];\n\n/** Assert messages by program counter, for the current build of each contract. */\nexport const VOTE_ERRORS: Record<"vote" | "factory" | "list", Record<number, string>> = ${JSON.stringify(errors)};\n\n/** App creation deposits (µALGO) charged to the creating account, for the current build. */\nexport const APP_DEPOSITS = ${JSON.stringify(deposits)} as const;\n`
);
console.log(`Vote template ${hash}${known.includes(hash) ? " (unchanged)" : " (added)"}`);
